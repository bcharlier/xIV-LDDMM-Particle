"""
3D Affine Registration in cross-modality for Label Permutation
========================================
"""


####################################################################
#This script demonstrates the use of the :mod:`xmodmap` framework for 3D registration of two segmentations of the entorhinal and hippocampal regions (source and target, with target label permutation) using an affine transformation models.


###################################################################
# Import libraries and set device
#
import os
import numpy as np
import torch
import xmodmap
import xmodmap.preprocess

# set random seed
device = "cuda" if torch.cuda.is_available() else "cpu"
torch.set_default_device(device)

###################################################################
# Data loading and preprocessing
#
data_dir = os.path.join( "..", "data", "3D_MTL")

source_file = os.path.join(data_dir, "MTL_lf_123.pt")
target_file = os.path.join(data_dir, "MTL_lf_231.pt")
S, w_S, zeta_S = torch.load(source_file, map_location=device).values()
T, w_T, zeta_T = torch.load(target_file, map_location=device).values()
print(w_S.shape)
w_S = w_S.reshape(-1, 1)
w_T = w_T.reshape(-1, 1)
S, T, c_S, c_T = xmodmap.preprocess.centerData(S, T, w_S, w_T)
Stilde, Ttilde, s, m = xmodmap.preprocess.rescaleData(S, T)

####################################################################
# Following parameters are set for the registration problem. 
# The most important parameters are the kernel width for the RKHSs for 
# both the Hamiltonian term (deformation) and data attachment term (varifold)
#  in the loss function. 
# 

d = 3
dimEff = 3
sigmaRKHS = [0.1, 0.025]
sigmaVar = [0.1] 
cA, cT, cS = 1., 1., 10.
single = True
gamma = 0.1

###################################################################
# Varifold distance without boundaries. It is used to measure the 
# discrepancy between the deformed source and the target.
#
dataloss = xmodmap.distance.LossVarifoldNorm(sigmaVar, w_T, zeta_T, Ttilde)   
dataloss.weight = 1.

###################################################################
## Cross-Modality regularization term.
piLoss = xmodmap.distance.PiRegularizationSystem(zeta_S, zeta_T, w_T, norm=True)
piLoss.weight = 0.

###################################################################
# Affine deformations, that is rotation, translation and scaling, 
# are used to model the transformation between the source and target shapes. 
# These deformations are generated by integrating a Hamiltonian system over time given by class :class:`xmodmap.deformation.Hamiltonian`.
hamiltonian = xmodmap.deformation.Hamiltonian(sigmaRKHS, Stilde, cA=cA, cS=cS,  cT=cT, dimEff=dimEff, single=single, transform="affine")
hamiltonian.weight = gamma
shooting = xmodmap.deformation.Shooting(hamiltonian, nt=5)

###################################################################
# The objective function consists of three terms: the varifold distance
# measuring the discrepancy between the deformed source and target,
# the Hamiltonian regularizing the deformation, and the KL divergence
# regularizing the feature-mapping matrix.
#
# .. math::
#
#    \mathcal{L}(p, \pi_{ST}) =
#    \operatorname{VarifoldDistance}
#    \left(\phi^{v^p} \cdot S, T\right)
#    + \operatorname{Hamiltonian}(v^p)
#    + \operatorname{KL}\left(\pi_{ST} \| U_T\right)
#
# Here, :math:`\phi^{v^p}` denotes the flow generated by the Hamiltonian
# system with initial momentum :math:`p = (p_x, p_w)`.
# The matrix :math:`\pi_{ST}` represents the mapping from source to
# target features, while :math:`U_T` denotes the uniform distribution
# over target features. The KL-divergence term regularizes this mapping
# toward a uniform distribution.

variable_init = {
    "px": torch.zeros_like(Stilde).requires_grad_(True), # momentum for the source shape positions
    "pw": torch.zeros_like(w_S).requires_grad_(True),    # momentum for the source shape weights
    "qx": Stilde.clone().detach().requires_grad_(True),  # source shape positions
    "qw": w_S.clone().detach().requires_grad_(True),     # source shape weights
    "zeta_S": zeta_S,                                    # source features
    "pi_ST":piLoss.Pi_ST_init(w_S).clone().detach().requires_grad_(True),    # initial transfer function Pi_ST
}

#################################################################
# Optimization is performed over the source shape's initial momentum
# and weights. The initial momentum generates the deformation field
# that transforms the source shape to match the target.
#
# We define the variables to optimize—in this example, the initial
# momentum for the location and weights, and the transfer function 
# Pi_ST. These variables are updated during optimization. Other 
# variables may also require gradients (`requires_grad=True`) 
# without being optimized. They still need gradients because the 
# Hamiltonian system used to compute the
# deformation depends on them.

variable_to_optimize = ["px", "pw", "pi_ST"]

###################################################################
# We use a L-BFGS optimizer to minimize the loss function. The preconditioner 
# is used to scale the gradients of the variables to optimize, which can help with convergence.

precond = {
    "px": 1.,
    "pw": 1. / dimEff / w_S,
    "pi_ST": 1.,
}

loss = xmodmap.model.CrossModality(hamiltonian, shooting, dataloss, piLoss)
loss.init(variable_init, variable_to_optimize, precond=precond)
loss.optimize(10)

################################################################
# Plot source, target and deformed source (with time slider)
import xmodmap.plot

variables_optimum = loss.get_variables_optimized()
trajectory = shooting(*(variables_optimum[k] for k in ["px", "pw", "qx", "qw"]))

# actual (nonnegative) coupling, shape (n_zeta_S, n_zeta_T)
pi_ST = variables_optimum["pi_ST"].detach() ** 2   
with np.printoptions(precision=2, suppress=True):
    print("pi_ST =\n", pi_ST.detach().cpu().numpy())
    print("row sums:", pi_ST.sum(dim=1).detach().cpu().numpy())
    print("col sums:", pi_ST.sum(dim=0).detach().cpu().numpy())

scene = xmodmap.plot.plot_registration_3d(
    Stilde, w_S, zeta_S, Ttilde, w_T, zeta_T,
    trajectory, pi_ST,
    style="sphere",
    show=False,
)
scene.show(auto_close=False)


