"""
Mother class of every deformation mode.

Notation (same as xmodmap):
    qx : N x d   particle positions          (state)
    qw : N x 1   particle masses             (state)
    px : N x d   position momenta            (co-state)
    pw : N x 1   mass momenta                (co-state)

A mode is a family of velocity fields v_u, indexed by a control u with a
quadratic cost |u|^2 / 2.  Positions are transported by v and masses by its
divergence:

    dqx_i/dt = v_u(qx_i),      dqw_i/dt = qw_i * div v_u(qx_i).

The (reduced) Hamiltonian of the mode is

    H(p, q) = max_u  sum_i <px_i, v_u(qx_i)> + pw_i qw_i div v_u(qx_i) - |u|^2/2
            = |u*(p, q)|^2 / 2,

and the geodesic ("shooting") is the solution of Hamilton's equations

    dq/dt = dH/dp,     dp/dt = -dH/dq.

Because every parameter of the mode (kernel scales, coefficients, dimension,
number of time steps...) is stored on the instance, shooting is simply a
method of the Hamiltonian.  Children with an explicit solution of Hamilton's
equations set ``has_closed_form = True`` and implement ``flow_trajectory``;
the generic numerical integrators are then bypassed.
"""

import torch


class Hamiltonian:
    name = "hamiltonian"
    has_closed_form = False

    def __init__(self, d, nt=10, integrator="ralston"):
        if integrator not in self.INTEGRATORS:
            raise ValueError(f"Unknown integrator '{integrator}'. Choose one of {tuple(self.INTEGRATORS)}.")
        self.d = d
        self.nt = nt
        self.integrator = integrator

    # ------------------------------------------------------------------
    # To be implemented by children
    # ------------------------------------------------------------------
    def H(self, px, pw, qx, qw):
        """Value of the reduced Hamiltonian (a scalar tensor)."""
        raise NotImplementedError

    def velocity(self, px, pw, qx, qw, x):
        """Optimal velocity field v*(x) generated by (p, q), evaluated at points x (G x d)."""
        raise NotImplementedError

    def divergence(self, px, pw, qx, qw, x):
        """Divergence of the optimal velocity field at points x (G x 1)."""
        raise NotImplementedError

    def flow_trajectory(self, times, px, pw, qx, qw, X=None, wX=None):
        """Closed-form solution of Hamilton's equations at the given times (only if has_closed_form)."""
        raise NotImplementedError(f"{type(self).__name__} has no closed-form flow.")

    # ------------------------------------------------------------------
    # Generic API
    # ------------------------------------------------------------------
    def __call__(self, px, pw, qx, qw):
        return self.H(px, pw, qx, qw)

    def energies(self, px, pw, qx, qw):
        """Contribution of each mode to H (a dict). Overridden by MixedHamiltonian."""
        return {self.name: self.H(px, pw, qx, qw)}

    def get_params(self):
        return {"name": self.name, "nt": self.nt, "integrator": self.integrator}

    def __repr__(self):
        params = ", ".join(f"{k}={v}" for k, v in self.get_params().items() if k != "name")
        return f"{type(self).__name__}({params})"

    # ------------------------------------------------------------------
    # Hamilton's equations (by automatic differentiation of H)
    # ------------------------------------------------------------------
    def system(self, px, pw, qx, qw, X=None, wX=None):
        """
        Time derivatives (dpx, dpw, dqx, dqw[, dX, dwX]).

        Extra points (X, wX) are passively transported by the velocity field
        (xmodmap's HamiltonianSystemGrid / HamiltonianSystemBackwards).
        """
        with torch.enable_grad():
            state = [v if v.requires_grad else v.detach().requires_grad_(True) for v in (px, pw, qx, qw)]
            h = self.H(*state)
            grads = torch.autograd.grad(h, state, create_graph=True, allow_unused=True)
        Gpx, Gpw, Gqx, Gqw = [torch.zeros_like(s) if g is None else g for s, g in zip(state, grads)]

        out = (-Gqx, -Gqw, Gpx, Gpw)
        if X is not None:
            out += (
                self.velocity(px, pw, qx, qw, X),
                self.divergence(px, pw, qx, qw, X) * wX,
            )
        return out

    # ------------------------------------------------------------------
    # Numerical integrators: each returns the list of states at t_k = k/nt
    # ------------------------------------------------------------------
    @staticmethod
    def euler(system, x0, nt, deltat=1.0):
        x = tuple(v.clone() for v in x0)
        dt = deltat / nt
        traj = [x]
        for _ in range(nt):
            xdot = system(*x)
            x = tuple(v + dt * vd for v, vd in zip(x, xdot))
            traj.append(x)
        return traj

    @staticmethod
    def ralston(system, x0, nt, deltat=1.0):
        """Second order Ralston scheme (default of xmodmap)."""
        x = tuple(v.clone() for v in x0)
        dt = deltat / nt
        traj = [x]
        for _ in range(nt):
            xdot = system(*x)
            xi = tuple(v + (2 * dt / 3) * vd for v, vd in zip(x, xdot))
            xdoti = system(*xi)
            x = tuple(v + (0.25 * dt) * (vd + 3 * vdi) for v, vd, vdi in zip(x, xdot, xdoti))
            traj.append(x)
        return traj

    @staticmethod
    def rk4(system, x0, nt, deltat=1.0):
        x = tuple(v.clone() for v in x0)
        dt = deltat / nt
        traj = [x]
        for _ in range(nt):
            k1 = system(*x)
            k2 = system(*(v + 0.5 * dt * k for v, k in zip(x, k1)))
            k3 = system(*(v + 0.5 * dt * k for v, k in zip(x, k2)))
            k4 = system(*(v + dt * k for v, k in zip(x, k3)))
            x = tuple(
                v + (dt / 6.0) * (a + 2 * b + 2 * c + e) for v, a, b, c, e in zip(x, k1, k2, k3, k4)
            )
            traj.append(x)
        return traj

    INTEGRATORS = {"euler": euler.__func__, "ralston": ralston.__func__, "rk4": rk4.__func__}

    def integrate(self, x0, nt=None, integrator=None):
        """Numerically integrate Hamilton's equations from x0 = (px, pw, qx, qw[, X, wX])."""
        nt = self.nt if nt is None else nt
        scheme = self.INTEGRATORS[self.integrator if integrator is None else integrator]
        return scheme(self.system, tuple(x0), nt)

    # ------------------------------------------------------------------
    # Shooting (former xmodmap.deformation.Shooting* classes)
    # ------------------------------------------------------------------
    def shoot(self, px, pw, qx, qw, X=None, wX=None, nt=None):
        """
        Geodesic shooting from the initial momenta.

        Returns the list of states at t_k = k / nt, k = 0..nt. Each state is
        (px, pw, qx, qw) or (px, pw, qx, qw, X, wX) if extra points are given
        (former ``Shooting`` and ``ShootingGrid``).  Uses the closed-form flow
        when the mode has one.
        """
        nt = self.nt if nt is None else nt
        x0 = (px, pw, qx, qw) if X is None else (px, pw, qx, qw, X, self._default_mass(X, wX))
        if self.has_closed_form:
            return [tuple(v.clone() for v in x0)] + self.flow_trajectory(
                [k / nt for k in range(1, nt + 1)], *x0
            )
        return self.integrate(x0, nt=nt)

    def endpoint(self, px, pw, qx, qw, X=None, wX=None):
        """Final state of the shooting (t = 1) only."""
        if self.has_closed_form:
            x0 = (px, pw, qx, qw) if X is None else (px, pw, qx, qw, X, self._default_mass(X, wX))
            return self.flow_trajectory([1.0], *x0)[0]
        return self.shoot(px, pw, qx, qw, X=X, wX=wX)[-1]

    def shoot_backward(self, px1, pw1, qx1, qw1, X, wX=None, nt=None):
        """
        Backward shooting from the final state (former ``ShootingBackwards``).

        The Hamiltonian is even in p, so reversing time amounts to flipping the
        final momenta.  The last state contains the points X pulled back to t = 0.
        """
        return self.shoot(-px1, -pw1, qx1, qw1, X=X, wX=wX, nt=nt)

    @staticmethod
    def _default_mass(X, wX):
        return torch.ones(X.shape[0], 1, dtype=X.dtype, device=X.device) if wX is None else wX
