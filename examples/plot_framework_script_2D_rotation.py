"""
2D Rigid Registration in single modality
========================================
"""


####################################################################
#This script demonstrates the use of the mod:`xmodmap` framework for 2D registration of two representation of amygdala (source and target) using a rigid transformation model.
#



###################################################################
# Import libraries and set device
#

import os
import torch
import xmodmap
import xmodmap.preprocess

# set random seed
device = "cuda" if torch.cuda.is_available() else "cpu"
torch.set_default_device(device)


###################################################################
# Data loading and preprocessing
#

data_dir = os.path.join("..", "data", "2D_amygdala")

source_file = os.path.join(data_dir, "onehot.pt")
target_file = os.path.join(data_dir, "onehot_rotation.pt")
S, w_S, zeta_S = torch.load(source_file, map_location=device).values()
T, w_T, zeta_T = torch.load(target_file, map_location=device).values()

Stilde, Ttilde, s, m = xmodmap.preprocess.rescaleData(S, T)


####################################################################
# Folowing parameters are set for the registration problem. 
# The main important parameters are the kernel width for the RKHSs for both the Hamiltonian term (deformation) and data attachment term (varifold) in the loss function. 
# 
 
d = 2
dimEff = 2
sigmaRKHS = []   # Rigid transformation does not require a kernel width for the RKHS
sigmaVar = [0.2] 
cA, cT, cS = 1., 1., 1.
single = False
gamma = 0.1

###################################################################
# Varifold distance without boundaries. It is used to measure the discrepancy between the deformed source and the target and do not require any point-to-point correspondences between the two shapes.
#
dataloss = xmodmap.distance.LossVarifoldNorm(sigmaVar, w_T, zeta_T, Ttilde)   
dataloss.weight = 1.

###################################################################
# Affine deformations, that is rotation, translation and scaling, are used to model the transformation between the source and target shapes. These deformations are generated by integrating a Hamiltonian system over time given by class :class:`xmodmap.deformation.Hamiltonian`.

hamiltonian = xmodmap.deformation.Hamiltonian(sigmaRKHS, Stilde, cA=cA, cS=cS,  cT=cT, dimEff=dimEff, single=single, transform="affine")
hamiltonian.weight = gamma
shooting = xmodmap.deformation.Shooting(hamiltonian, nt=1) 

###################################################################
# The loss function consisting of the varifold distance and the Hamiltonian term.
# 
# ..math::
#     \mathcal{L}(p) = \text{VarifoldDistance}( \phi^{v^p} \cdot S, T) + \gamma \text{Hamiltonian}(v^p)
#
# where $\phi^{v^p}$ is defined as the flow of the Hamiltonian system generated by the initial momentum $p= (p_x, p_w)$.


variable_init = {
    "px": torch.zeros_like(Stilde).requires_grad_(True),   # momentum for the source shape positions
    "pw": torch.zeros_like(w_S).requires_grad_(True),      # momentum for the source shape weights
    "qx": Stilde.clone().detach().requires_grad_(True),    # source shape positions
    "qw": w_S.clone().detach().requires_grad_(True),       # source shape weights
    "zeta_S": zeta_S,                                      # source features
}


#################################################################
# Optimization is performed over the source shape's initial momentum
# and weights. The initial momentum generates the deformation field
# that transforms the source shape to match the target.
#
# We define the variables to optimize—in this example, the initial
# momentum for the location and weights. These variables are updated
# during optimization. Other variables may also require gradients
# (`requires_grad=True`) without being optimized. They still need
# gradients because the Hamiltonian system used to compute the
# deformation depends on them.

variable_to_optimize = ["px", "pw"]

###################################################################
# We use a L-BFGS optimizer to minimize the loss function. The preconditioner is used to scale the gradients of the variables to optimize, which can help with convergence.

precond = {
    "px": 1.,
    "pw": 1. / dimEff / w_S,
}

loss = xmodmap.model.SingleModality(hamiltonian, shooting, dataloss)
loss.init(variable_init, variable_to_optimize, precond=precond)
loss.optimize(10)

################################################################
# Plot source, target and deformed source (with time slider)

import xmodmap.plot

variables_optimum = loss.get_variables_optimized()
trajectory = xmodmap.deformation.Shooting(hamiltonian, nt=30)(*(variables_optimum[k] for k in ["px", "pw", "qx", "qw"]))

scene = xmodmap.plot.plot_registration_3d(Stilde, w_S, zeta_S, Ttilde, w_T, zeta_T, trajectory, show=False)
scene.show()
